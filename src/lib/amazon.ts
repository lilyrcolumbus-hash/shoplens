// Amazon orders client — reads the worker's cached Amazon orders.
import type { Order } from './etsy'
import { workerUrl, workerFetch } from './worker'


export async function fetchAmazonOrders(): Promise<Order[]> {
  const resp = await workerFetch(`${workerUrl()}/amazon/orders`)
  if (!resp.ok) throw new Error(`Amazon fetch failed: ${resp.status}`)
  return (await resp.json()) as Order[]
}

// Amazon Sales & Traffic (sessions, conversion, Buy Box) from the SP-API report.
export interface AmazonTraffic {
  updatedAt: number
  rangeDays: number
  totals: {
    sessions: number
    pageViews: number
    units: number
    sales: number
    currency: string
    conversionPct: number
    buyBoxPct: number
  }
  daily: Array<{ date: string; sessions: number; units: number; sales: number }>
}

// 'pending' = report still being generated by Amazon (async, takes minutes).
export async function fetchAmazonTraffic(): Promise<AmazonTraffic | 'pending'> {
  const resp = await workerFetch(`${workerUrl()}/amazon/traffic`)
  if (!resp.ok) throw new Error(`Amazon traffic fetch failed: ${resp.status}`)
  const j = (await resp.json()) as { status?: string }
  if (j.status === 'pending') return 'pending'
  return j as AmazonTraffic
}

// Amazon listings (status, stock, price) from the Merchant Listings report.
export interface AmazonListing {
  sku: string
  asin: string
  title: string
  price: number
  quantity: number
  status: string
  url: string
  // Per-product traffic (last ~30d), joined from the Sales & Traffic report when available.
  sessions?: number
  pageViews?: number
  conversionPct?: number
}

export async function fetchAmazonListings(): Promise<AmazonListing[] | 'pending'> {
  const resp = await workerFetch(`${workerUrl()}/amazon/listings`)
  if (!resp.ok) throw new Error(`Amazon listings fetch failed: ${resp.status}`)
  const j = (await resp.json()) as { status?: string; listings?: AmazonListing[] }
  if (j.status === 'pending') return 'pending'
  return j.listings ?? []
}
